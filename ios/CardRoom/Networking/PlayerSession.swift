import Foundation

/// Mirrors the web app's `localStorage` usage (`cardroom_player_id` / `cardroom_room_code`) via
/// `UserDefaults` — this is what lets rejoining the same room from this device reuse the same
/// player row instead of creating a duplicate seat.
enum PlayerSession {
    private static let playerIdKey = "cardroom_player_id"
    private static let roomCodeKey = "cardroom_room_code"

    static var playerId: String? {
        get { UserDefaults.standard.string(forKey: playerIdKey) }
        set { UserDefaults.standard.set(newValue, forKey: playerIdKey) }
    }

    static var roomCode: String? {
        get { UserDefaults.standard.string(forKey: roomCodeKey) }
        set { UserDefaults.standard.set(newValue, forKey: roomCodeKey) }
    }

    static func save(playerId: String, roomCode: String) {
        self.playerId = playerId
        self.roomCode = roomCode
    }
}

/// Mirrors `generateFunName()` in card-room's `src/lib/names.ts` — same three word lists, so
/// this app's placeholder names read identically to ones generated by the web app (e.g.
/// "Mr Funky Carrot").
enum FunName {
    private static let titles = ["Mr", "Ms", "Mx", "Dr", "Sir", "Dame", "Lord", "Lady", "Captain", "Professor", "Duke", "Baron", "Esq", "Count"]
    private static let adjectives = ["Funky", "Dubious", "Sneaky", "Wobbly", "Spicy", "Grumpy", "Fancy", "Mysterious", "Soggy", "Zesty", "Gallant", "Sly", "Plucky", "Rowdy", "Silly", "Dapper", "Feral", "Nifty"]
    private static let produce = ["Carrot", "Potato", "Turnip", "Mango", "Kale", "Pickle", "Broccoli", "Eggplant", "Radish", "Kiwi", "Parsnip", "Cabbage", "Fig", "Beet", "Yam", "Avocado", "Leek", "Papaya"]

    static func generate() -> String {
        "\(titles.randomElement()!) \(adjectives.randomElement()!) \(produce.randomElement()!)"
    }
}
